def readme(name: str, recipe_dict: dict, heal_ws: str) -> str:
    steps = recipe_dict.get("steps", [])
    lines = [f"# {name}", "",
             "Standalone Chrome extension generated by **ai-web-auto** from a",
             "recipe distilled from a self-play job. It replays the recipe over",
             "CDP; loading it is developer-mode / unpacked.", "",
             f"- **Objective:** {recipe_dict.get('objective') or '(none recorded)'}",
             f"- **Start URL:** {recipe_dict.get('start_url') or '(none)'}",
             f"- **Steps:** {len(steps)}",
             f"- **Source job:** `{recipe_dict.get('job_id', '')}`", "",
             "## Load it", "",
             "1. `chrome://extensions` → Developer mode ON",
             "2. Load unpacked → select this folder",
             "3. Open the target site, click the extension, press **Run recipe**", "",
             "## Self-healing", "",
             "If a selector no longer resolves, the extension asks the local",
             f"ai-web-auto backend (`{heal_ws}`) to re-discover it once. That is",
             "best-effort: with the backend down (or no `ANTHROPIC_API_KEY`) the",
             "step fails and the run halts — the extension still works standalone,",
             "it just won't auto-repair.", "",
             "## Steps", ""]
    for i, s in enumerate(steps, 1):
        detail = s.get("selector", "")
        if s.get("action") == "type" and s.get("text"):
            detail += f'  ← "{s["text"]}"'
        lines.append(f"{i}. `{s.get('action')}` {detail}")
    lines.append("")
    lines.append("Regenerate with: "
                 "`python -m ai_web_auto_backend.jobs generate --job <id> --name <slug>`")
    return "\n".join(lines)
