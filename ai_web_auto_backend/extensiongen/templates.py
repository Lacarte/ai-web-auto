"""File bodies for a generated standalone extension.

Everything here is a pure string template filled from a Recipe — no LLM, no
network. The generated service worker replays the recipe deterministically over
CDP (the same Input.insertText / trusted-mouse techniques the platform proved),
and falls back to the ai-web-auto backend for a one-shot LLM re-discovery when a
selector no longer resolves. That fallback is best-effort: if the backend is
down or ANTHROPIC_API_KEY is unset, the step fails loudly and the run halts,
so the extension stays useful even fully standalone.
"""

from __future__ import annotations

import json

# ---------------------------------------------------------------------------
# manifest.json
# ---------------------------------------------------------------------------

def manifest(name: str, description: str, heal_ws: str) -> str:
    data = {
        "manifest_version": 3,
        "name": name,
        "version": "1.0.0",
        "description": description or f"Replays a recipe learned by ai-web-auto ({name}).",
        "permissions": [
            "activeTab", "tabs", "scripting", "debugger", "storage", "alarms",
        ],
        # <all_urls> so the replayer can drive whatever site the recipe targets,
        # and reach the local heal backend. A generated extension is loaded
        # unpacked by its author, not published, so this is scoped by intent.
        "host_permissions": ["<all_urls>"],
        "background": {"service_worker": "js/background.js", "type": "module"},
        "action": {"default_popup": "html/popup.html"},
    }
    return json.dumps(data, indent=2)


# ---------------------------------------------------------------------------
# js/recipe.js — the data, emitted as a module the worker imports
# ---------------------------------------------------------------------------

def recipe_module(recipe_dict: dict, heal_ws: str) -> str:
    payload = json.dumps(recipe_dict, indent=2)
    return (
        "// Generated by ai-web-auto extensiongen. Do not hand-edit — regenerate\n"
        "// with: python -m ai_web_auto_backend.jobs generate --job <id> --name <slug>\n"
        f"export const RECIPE = {payload};\n"
        f"export const HEAL_WS = {json.dumps(heal_ws)};\n"
    )


# ---------------------------------------------------------------------------
# js/background.js — the deterministic CDP replayer + graceful heal fallback
# ---------------------------------------------------------------------------

BACKGROUND_JS = r"""/**
 * Generated recipe replayer.
 *
 * Runs RECIPE steps top to bottom against one tab via CDP — the trusted-input
 * techniques ai-web-auto proved: Input.insertText for typing (React-safe),
 * Input.dispatchMouseEvent for clicks (trusted, Radix-safe). On a selector that
 * no longer resolves it asks the local ai-web-auto backend for a one-shot
 * re-discovery (HEAL_WS); if that backend is unreachable the step fails and the
 * run halts, so the extension still works fully standalone.
 */

import { RECIPE, HEAL_WS } from "./recipe.js";

let RUN = { active: false, step: 0, total: 0, log: [], tabId: null };

// ── popup wiring ────────────────────────────────────────────────────────────
chrome.runtime.onMessage.addListener((msg, _sender, sendResponse) => {
  if (msg.channel !== "popup-to-bg") return;
  if (msg.action === "run") { runRecipe().then(() => sendResponse({ ok: true })); return true; }
  if (msg.action === "status") { sendResponse(status()); }
});

function status() {
  return { active: RUN.active, step: RUN.step, total: RUN.total, log: RUN.log.slice(-40) };
}
function note(text, cls = "info") {
  RUN.log.push({ ts: Date.now(), text, cls });
  console.log("[replay]", text);
}

// ── CDP session ─────────────────────────────────────────────────────────────
const attached = new Set();
async function attach(tabId) {
  if (attached.has(tabId)) return;
  await chrome.debugger.attach({ tabId }, "1.3");
  attached.add(tabId);
}
async function detach(tabId) {
  if (!attached.has(tabId)) return;
  try { await chrome.debugger.detach({ tabId }); } catch { /* already gone */ }
  attached.delete(tabId);
}
function send(tabId, method, params = {}) {
  return chrome.debugger.sendCommand({ tabId }, method, params);
}
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

// ── DOM helpers (MAIN world, bypasses page CSP) ─────────────────────────────
async function locate(tabId, method, selector) {
  const [{ result } = {}] = await chrome.scripting.executeScript({
    target: { tabId },
    world: "MAIN",
    args: [method, selector],
    func: (method, selector) => {
      let el = null;
      if (method === "xpath") {
        const r = document.evaluate(selector, document, null,
          XPathResult.FIRST_ORDERED_NODE_TYPE, null);
        el = r.singleNodeValue;
      } else {
        el = document.querySelector(selector);
      }
      if (!el) return null;
      const rect = el.getBoundingClientRect();
      if (rect.width === 0 && rect.height === 0) return null; // hidden ≠ found
      return { x: Math.round(rect.left + rect.width / 2),
               y: Math.round(rect.top + rect.height / 2) };
    },
  });
  return result || null;
}

async function cdpClick(tabId, x, y) {
  await send(tabId, "Input.dispatchMouseEvent", { type: "mousePressed", x, y, button: "left", clickCount: 1 });
  await send(tabId, "Input.dispatchMouseEvent", { type: "mouseReleased", x, y, button: "left", clickCount: 1 });
}
async function cdpType(tabId, text) {
  for (const ch of text) { await send(tabId, "Input.insertText", { text: ch }); await sleep(5); }
}
async function cdpClear(tabId) {
  await send(tabId, "Input.dispatchKeyEvent", { type: "keyDown", key: "a", code: "KeyA", windowsVirtualKeyCode: 65, modifiers: 2 });
  await send(tabId, "Input.dispatchKeyEvent", { type: "keyUp", key: "a", code: "KeyA", windowsVirtualKeyCode: 65, modifiers: 2 });
  await sleep(30);
  await send(tabId, "Input.dispatchKeyEvent", { type: "keyDown", key: "Backspace", code: "Backspace", windowsVirtualKeyCode: 8 });
  await send(tabId, "Input.dispatchKeyEvent", { type: "keyUp", key: "Backspace", code: "Backspace", windowsVirtualKeyCode: 8 });
  await sleep(50);
}

// ── one-shot LLM re-discovery via the ai-web-auto backend ───────────────────
// Best-effort: resolves to a new selector string, or null if the backend is
// unreachable / declines. Never throws — a dead backend must degrade to a plain
// step failure, not a hang.
function heal(step) {
  return new Promise((resolve) => {
    let done = false;
    const finish = (v) => { if (!done) { done = true; try { ws.close(); } catch {} resolve(v); } };
    let ws;
    try { ws = new WebSocket(HEAL_WS); } catch { return finish(null); }
    const timer = setTimeout(() => finish(null), 8000);
    ws.onopen = () => {
      ws.send(JSON.stringify({ type: "auth", token: "local-dev-token" }));
      ws.send(JSON.stringify({ type: "heal_request", action: step.action, selector: step.selector }));
    };
    ws.onmessage = (ev) => {
      let m; try { m = JSON.parse(ev.data); } catch { return; }
      if (m.type === "heal_response" && m.selector) { clearTimeout(timer); finish(m.selector); }
    };
    ws.onerror = () => { clearTimeout(timer); finish(null); };
    ws.onclose = () => { clearTimeout(timer); finish(null); };
  });
}

// ── the replay loop ─────────────────────────────────────────────────────────
async function runRecipe() {
  if (RUN.active) return;
  RUN = { active: true, step: 0, total: RECIPE.steps.length, log: [], tabId: null };
  note(`Replaying ${RECIPE.steps.length} steps: ${RECIPE.objective || "(no objective)"}`);

  let tab = (await chrome.tabs.query({ active: true, currentWindow: true }))[0];
  try {
    for (let i = 0; i < RECIPE.steps.length; i++) {
      RUN.step = i + 1;
      const step = RECIPE.steps[i];

      if (step.action === "navigate") {
        note(`(${RUN.step}/${RUN.total}) navigate ${step.selector}`);
        await chrome.tabs.update(tab.id, { url: step.selector });
        await waitForComplete(tab.id);
        tab = await chrome.tabs.get(tab.id);
        continue;
      }

      await attach(tab.id);
      let pos = await locate(tab.id, step.method, step.selector);

      if (!pos) {
        note(`(${RUN.step}/${RUN.total}) selector miss: ${step.selector} — asking backend to re-discover`, "warn");
        const healed = await heal(step);
        if (healed) {
          note(`  healed → ${healed}`, "info");
          pos = await locate(tab.id, step.method, healed);
        }
      }
      if (!pos) {
        note(`FAILED at step ${RUN.step}/${RUN.total}: ${step.action} ${step.selector} — selector not found`, "error");
        break;
      }

      if (step.action === "click") {
        note(`(${RUN.step}/${RUN.total}) click ${step.selector}`);
        await cdpClick(tab.id, pos.x, pos.y);
      } else if (step.action === "type") {
        note(`(${RUN.step}/${RUN.total}) type into ${step.selector}`);
        await cdpClick(tab.id, pos.x, pos.y);        // focus first
        if (step.clear_first) await cdpClear(tab.id);
        await cdpType(tab.id, step.text || "");
      }
      await sleep(250);
    }
    if (RUN.step === RUN.total) note("Recipe complete.", "success");
  } catch (e) {
    note(`Replay error: ${e && e.message ? e.message : e}`, "error");
  } finally {
    if (tab) await detach(tab.id);
    RUN.active = false;
  }
}

function waitForComplete(tabId, timeoutMs = 15000) {
  return new Promise((resolve) => {
    const deadline = Date.now() + timeoutMs;
    const tick = async () => {
      try {
        const t = await chrome.tabs.get(tabId);
        if (t.status === "complete" || Date.now() > deadline) return resolve();
      } catch { return resolve(); }
      setTimeout(tick, 200);
    };
    tick();
  });
}

// Keep the MV3 worker alive across a run.
chrome.alarms.create("keepalive", { periodInMinutes: 0.25 });
chrome.alarms.onAlarm.addListener(() => {});
"""

